/* OPERADORES ARITIMETICOS */
console.log("OPERADORES ARITIMETICOS\n")

console.log(`5 + 2 = ${5 + 2}`)		// Soma
console.log(`5 - 2 = ${5 - 2}`)		// Subtração
console.log(`5 * 2 = ${5 * 2}`)		// Multiplicação
console.log(`5 / 2 = ${5 / 2}`)		// Divisão Real
console.log(`5 % 2 = ${5 % 2}`)		// Resto da Divisão
console.log(`5 ** 2 = ${5 ** 2}`)	// Exponenciação


